#!/usr/bin/env python3
"""干扰车 A（蓝色）：全地图闭环巡游。

闭环要素（用户要求「不得缺失」）：
  主干道 → 穿过斑马线 → 下到停车场车道口 → 停车场内绕一圈 → 回到主干道
  → 东侧小路 → 南侧道路 → 西侧小路 → 回到主干道

靠右行驶的取值（road_* 的几何见 tools/build_world.py）：
  主路东行 y=17（南半幅）、西街北行 x=-27、东街南行 x=27、
  南侧道路西行 **y=-37.2**（靠路面南侧走，让开 B 排平行位的泊车走廊，
  详见 ROUTE 里那一段的注释）。
首尾相接：最后一个点 (-22,14) 在环路起点 (-14,17) 的西侧，方向一致，闭合处不用调头。
"""

from .path_agent import PathAgent

ROUTE = [
    (-14.0, 17.0),     # 主路东行
    (-8.0, 17.0),
    (-3.0, 14.0),      # 进停车场：南行走**西侧**车道（右侧通行）
    (-3.0, 10.0),
    (-3.0, 4.0),
    (-6.0, 1.0),       # 切入西侧过道
    (-8.0, -2.0),
    # ---- 场内单向环行（逆时针，只允许这一个方向）----
    # 西过道只准南行、南过道只准东行、东过道只准北行。加中段航点是必要的：
    # 只写端点时圆角会把转角切得很深，刀口正好落在两排车位口上（实测两台车
    # 都在场内深过道处各停过一次）。
    (-8.0, -10.0),
    (-8.0, -19.0),
    (0.0, -19.0),      # 南侧过道中段
    (8.0, -19.0),
    (8.0, -10.0),
    (8.0, -2.0),
    (6.0, 1.0),        # 切出东侧过道
    (3.0, 4.0),        # 出停车场：北行走**东侧**车道
    (3.0, 10.0),
    (3.0, 14.0),
    (10.0, 17.0),      # 回到主路东行
    (22.0, 17.0),      # 穿过东路口西侧斑马线 x=21.8
    (38.0, 17.0),      # 穿过东路口东侧斑马线 x=36.2
    (30.0, 22.0),      # 路口内右转
    (27.0, 12.0),      # 进东侧小路南行
    (27.0, -26.0),
    (20.0, -37.2),     # 右转上南侧道路西行
    # 南侧道路路面 y∈[-39,-30]（build_world.py 的 `road_south` 中心 −34.5、
    # 宽 9 m），但**北半幅 y≈−34.5 正是 B 排平行位的泊车走廊**：
    # 平行位的预备位姿在 y≈−34.70（§6.36），车身占 [−33.775,−35.625]，
    # 与原来 y=−34.5 的航线（车身 [−33.575,−35.425]）几乎完全重合 ——
    # 真机 B3 三轮都是在这里和自车贴死（自车护栏读数 lon=−2.17 / lat=−0.90，
    # 车体间隙 0.00 m），而且两台车长期并行还让 slam_toolbox 的扫描匹配
    # 退化（B3 位姿对照 RMSE 1.60 m，B1 只有 0.78 m）。
    # 改成走 y=−37.2：车身 [−36.275,−38.125]，离路面南沿（−39）还有 0.875 m，
    # 离自车预备位姿北沿（−33.775）有 2.5 m，泊车走廊彻底让开。
    (0.0, -37.2),
    (-20.0, -37.2),
    (-27.0, -26.0),    # 右转进西侧小路北行
    (-27.0, 8.0),
    (-22.0, 14.0),     # 回到主路东行
]


def main(args=None):
    import rclpy
    from rclpy.executors import ExternalShutdownException
    rclpy.init(args=args)
    node = PathAgent('traffic_driver', ROUTE)
    try:
        rclpy.spin(node)
    except (KeyboardInterrupt, ExternalShutdownException):
        pass
    node.destroy_node()
    if rclpy.ok():
        rclpy.shutdown()


if __name__ == '__main__':
    main()
